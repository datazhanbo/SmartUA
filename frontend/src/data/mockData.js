// ==================== 辅助函数 ====================

// 根据 ID 获取 Campaign
export const getCampaignById = (id) => {
  return MOCK_CAMPAIGNS.find(c => c.id === parseInt(id) || c.id.toString() === id.toString())
}

// 根据名称获取 Campaign
export const getCampaignByName = (name) => {
  return MOCK_CAMPAIGNS.find(c => c.name === name)
}

// 获取所有激活的 Campaign
export const getActiveCampaigns = () => {
  return MOCK_CAMPAIGNS.filter(c => c.status === 'running')
}

// 根据素材 ID 获取关联的 Campaign
export const getCampaignsByCreative = (creativeId) => {
  const creative = MOCK_CREATIVES.find(c => c.id === creativeId)
  if (!creative) return []
  return creative.linked_campaigns.map(id => getCampaignById(id)).filter(Boolean)
}

// 根据意图 ID 获取关联的 Campaign
export const getCampaignsByIntent = (intentId) => {
  const intent = MOCK_INTENT_EXECUTIONS.find(i => i.id === intentId)
  if (!intent) return []
  return intent.affected_campaigns.map(c => getCampaignById(c.id)).filter(Boolean)
}

